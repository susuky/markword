test('portable HTML retains folded state, prints every child, and restores the editable source', async ({ page, context }) => {
  const original = '# Portable toggles\n\n<details>\n<summary>Hidden folder</summary>\n\nHidden child **content**.\n\n<details>\n<summary>Inner folder</summary>\n\nDeep child content.\n\n</details>\n\n</details>\n'
  await single(page, original)
  await page.getByRole('button', { name: 'Export', exact: true }).click()
  const downloading = page.waitForEvent('download')
  await page.getByRole('button', { name: /^Portable HTML/ }).click()
  const download = await downloading
  const html = await readFile((await download.path())!, 'utf8')
  expect(JSON.parse(html.match(/id="markword-source">(.*?)<\/script>/s)![1]).markdown).toBe(original)
  expect(html).not.toContain('data-block-handle')
  const reader = await context.newPage()
  await reader.setContent(html)
  await expect(reader.locator('details .markdown-toggle-content').first()).toBeHidden()
  await reader.emulateMedia({ media: 'print' })
  await expect(reader.getByText('Hidden child content.')).toBeVisible()
  await expect(reader.getByText('Deep child content.')).toBeVisible()
  await reader.close()
  await page.locator('input[type=file]').first().setInputFiles({ name: 'portable-toggles.html', mimeType: 'text/html', buffer: Buffer.from(html) })
  await expect(body(page).locator('details')).toHaveCount(2)
  await expect(body(page).locator('details').first()).not.toHaveAttribute('open')
  expect(await source(page)).toBe(original)
})

test('mobile list handles leave room for markers and never expose folded children', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.locator('.cm-content').fill('- Parent\n  - First child\n  - Second child\n- Last\n\n<details>\n<summary>Folded folder</summary>\n\nHidden paragraph.\n\n</details>\n')
  await page.getByRole('tab', { name: 'Preview', exact: true }).click()
  await expect(page.locator('[data-block-handle]')).toHaveCount(5)
  const items = body(page).locator('li')
  const boxes = []
  for (const item of await items.all()) {
    const grip = await handle(page, item)
    const box = (await grip.boundingBox())!
    const content = (await item.boundingBox())!
    expect(content.x - box.x - box.width).toBeGreaterThanOrEqual(16)
    boxes.push(box)
  }
  boxes.sort((a, b) => a.y - b.y)
  for (let index = 1; index < boxes.length; index++) expect(boxes[index].y - boxes[index - 1].y).toBeGreaterThanOrEqual(44)
  await body(page).locator('summary').press('Enter')
  await expect(page.locator('[data-block-handle]')).toHaveCount(6)
  await body(page).locator('summary').press('Enter')
  await expect(page.locator('[data-block-handle]')).toHaveCount(5)
})
