import { expect, test } from './shared-workspace-fixture'

test('Escape dismisses an export menu before closing the document sidebar', async ({ page }) => {
  await page.goto('/')
  await page.locator('.cm-content').fill('# Navigation check')
  const documents = page.getByRole('complementary', { name: 'Documents', exact: true })
  await page.locator('.activity-rail').getByRole('button', { name: 'Documents', exact: true }).click()
  await expect(documents).toBeVisible()
  const exportButton = page.getByRole('button', { name: 'Export', exact: true })
  await exportButton.click()
  await expect(page.locator('.export-menu')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.locator('.export-menu')).toHaveCount(0)
  await expect(documents).toBeVisible()
  await expect(exportButton).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(documents).toHaveCount(0)
})

test('mobile outline reports its actual expanded state through toggling and navigation', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto('/')
  await page.locator('.cm-content').fill('# First heading\n\n## Second heading\n\nKeep writing.')
  const outline = page.locator('.activity-rail').getByRole('button', { name: 'Document outline', exact: true })
  await expect(outline).toHaveAttribute('aria-expanded', 'false')
  await expect(page.locator('.outline-panel')).toBeHidden()
  await outline.click()
  await expect(outline).toHaveAttribute('aria-expanded', 'true')
  await expect(page.locator('.outline-panel')).toBeVisible()
  await page.locator('.outline-panel nav').getByRole('button', { name: 'Second heading', exact: true }).click()
  await expect(page.locator('.outline-panel')).toBeHidden()
  await expect(outline).toHaveAttribute('aria-expanded', 'false')
  await outline.click()
  await expect(outline).toHaveAttribute('aria-expanded', 'true')
  await outline.click()
  await expect(page.locator('.outline-panel')).toBeHidden()
  await expect(outline).toHaveAttribute('aria-expanded', 'false')
  await expect(page.getByRole('tab', { name: 'Editor', exact: true })).toHaveAttribute('aria-selected', 'true')
})


test('focus mode moves typing into the editor and returns to the previous view and control', async ({ page }) => {
  await page.goto('/')
  await page.locator('.cm-content').fill('# Focus check')
  await page.getByRole('button', { name: 'Write', exact: true }).click()
  await expect(page.locator('.pane--editor')).toBeHidden()
  const focus = page.getByRole('button', { name: 'Toggle focus mode', exact: true })
  await focus.click()
  await expect(page.locator('.cm-content')).toBeFocused()
  await page.keyboard.press('Control+End')
  await page.keyboard.insertText('\n\nTyped while focused.')
  await expect(page.locator('.cm-content')).toContainText('Typed while focused.')
  await page.keyboard.press('Escape')
  await expect(page.locator('.pane--editor')).toBeHidden()
  await expect(page.locator('.pane--preview')).toBeVisible()
  await expect(page.locator('.markdown-body')).toContainText('Typed while focused.')
  await expect(focus).toBeFocused()
})
