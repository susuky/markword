import { expect, test } from './shared-workspace-fixture'
import type { Page } from '@playwright/test'

const editor = (page: Page) => page.locator('.editor-host .cm-content')
const folds = (page: Page) => page.locator('.editor-host .cm-foldPlaceholder')
const library = (page: Page) => page.getByRole('complementary', { name: 'Documents', exact: true })

async function showDocuments(page: Page) {
  if (!await library(page).isVisible()) await page.locator('.activity-rail').getByRole('button', { name: 'Documents', exact: true }).click()
}

async function openDocument(page: Page, name: string) {
  await showDocuments(page)
  await library(page).locator('.document-list__open').filter({ has: page.getByText(name, { exact: true }) }).click()
  await expect(page.locator('.document-heading')).toContainText(name)
  await library(page).getByRole('button', { name: 'Close documents', exact: true }).click()
}

async function command(page: Page, name: string) {
  await page.keyboard.press('Control+k')
  await page.getByRole('textbox', { name: 'Search commands', exact: true }).fill(name)
  await page.locator('.command-palette__list button').filter({ hasText: name }).click()
}

test('each document remembers its own nested folds after switching and reloading', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await editor(page).fill('# Folding A\n\n## Child\n\nHidden child text.\n\n## Sibling\n\nVisible sibling text.\n\n# Second root\n\nAnother folded section.\n')
  await page.locator('.cm-foldGutter [title="Fold line"]:visible').nth(1).click()
  await expect(folds(page)).toHaveCount(1)
  await page.locator('.cm-foldGutter [title="Fold line"]:visible').first().click()
  await expect(editor(page)).not.toContainText('Visible sibling text.')
  await page.locator('.cm-foldGutter [title="Fold line"]:visible').first().click()
  await expect(folds(page)).toHaveCount(2)
  await showDocuments(page)
  const row = library(page).locator('.document-list > li').filter({ has: page.getByText('Folding A', { exact: true }) })
  await row.locator('summary').click()
  await row.getByRole('button', { name: 'Duplicate', exact: true }).click()
  await expect(page.locator('.document-heading')).toContainText('Copy of Folding A')
  await expect(folds(page)).toHaveCount(0)
  await openDocument(page, 'Folding A')
  await expect(folds(page)).toHaveCount(2)
  await expect(editor(page)).not.toContainText('Visible sibling text.')
  await page.locator('.cm-foldGutter [title="Unfold line"]:visible').first().click()
  await expect(folds(page)).toHaveCount(2)
  await expect(editor(page)).not.toContainText('Hidden child text.')
  await expect(editor(page)).toContainText('Visible sibling text.')
  await page.reload()
  await expect(folds(page)).toHaveCount(2)
  await expect(editor(page)).not.toContainText('Hidden child text.')
  await expect(editor(page)).not.toContainText('Another folded section.')
  await expect(page.locator('.save-status')).toHaveText('Saved locally')
  await page.screenshot({ path: '/tmp/markword-folding-restored.png', fullPage: false })
  await command(page, 'Unfold all sections')
  await expect(folds(page)).toHaveCount(0)
  await expect(editor(page)).toContainText('Hidden child text.')
  await openDocument(page, 'Copy of Folding A')
  await expect(folds(page)).toHaveCount(0)
  await openDocument(page, 'Folding A')
  await expect(folds(page)).toHaveCount(0)
  expect(errors).toEqual([])
})

test('folds survive editing before them, display changes and switching HTML mode', async ({ page }) => {
  await page.goto('/')
  await editor(page).fill('Preface.\n\n## Folded section\n\nHidden content.\n\n## Next\n\nVisible content.\n')
  await page.locator('.cm-foldGutter [title="Fold line"]:visible').first().click()
  await editor(page).focus()
  await page.keyboard.press('Control+Home')
  await page.keyboard.insertText('Inserted above.\n\n')
  await expect(folds(page)).toHaveCount(1)
  await page.locator('.markdown-body > p').first().locator('[contenteditable]').fill('Preview edit before the folded section.')
  await expect(folds(page)).toHaveCount(1)
  await page.getByRole('button', { name: 'Write', exact: true }).click()
  await expect(editor(page)).toBeHidden()
  await page.getByRole('button', { name: 'Split', exact: true }).click()
  await expect(folds(page)).toHaveCount(1)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('tab', { name: 'Editor', exact: true }).click()
  await expect(folds(page)).toHaveCount(1)
  await page.getByRole('tab', { name: 'Preview', exact: true }).click()
  await expect(editor(page)).toBeHidden()
  await page.getByRole('tab', { name: 'Editor', exact: true }).click()
  await expect(folds(page)).toHaveCount(1)
  await page.setViewportSize({ width: 1280, height: 720 })
  await page.getByRole('combobox', { name: 'Document mode', exact: true }).selectOption('text')
  await expect(folds(page)).toHaveCount(1)
  await page.getByRole('combobox', { name: 'Document mode', exact: true }).selectOption('markdown')
  await expect(page.locator('.save-status')).toHaveText('Saved locally')
  await page.getByRole('combobox', { name: 'Document mode', exact: true }).selectOption('html')
  await expect(page).toHaveTitle('Markword')
  await expect(page).toHaveURL(/\/$/)
  await page.getByRole('button', { name: 'Split', exact: true }).click()
  await page.getByRole('combobox', { name: 'Document mode', exact: true }).selectOption('markdown')
  await expect(folds(page)).toHaveCount(1)
  await expect(editor(page)).not.toContainText('Hidden content.')
  await page.reload()
  await expect(folds(page)).toHaveCount(1)
  await expect(editor(page)).toContainText('Preview edit before the folded section.')
  await page.locator('.cm-foldGutter [title="Unfold line"]:visible').click()
  await expect(editor(page)).toContainText('Hidden content.')
  await page.reload()
  await expect(folds(page)).toHaveCount(0)
})

test('folding keeps working when browser preference storage is full', async ({ page }) => {
  await page.goto('/')
  await editor(page).fill('# Storage test\n\nContent remains editable.\n')
  await page.evaluate(() => {
    const save = Storage.prototype.setItem
    Storage.prototype.setItem = function (key, value) {
      if (key.startsWith('markword.preference.editor-folding.')) throw new DOMException('Storage full', 'QuotaExceededError')
      save.call(this, key, value)
    }
  })
  await page.locator('.cm-foldGutter [title="Fold line"]:visible').click()
  await expect(folds(page)).toHaveCount(1)
  await page.locator('.cm-foldGutter [title="Unfold line"]:visible').click()
  await expect(editor(page)).toContainText('Content remains editable.')
  await editor(page).focus()
  await page.keyboard.press('Control+End')
  await page.keyboard.insertText('Still writing.')
  await expect(page.locator('.markdown-body')).toContainText('Still writing.')
  await expect(page.locator('.save-status')).toHaveText('Saved locally')
})
