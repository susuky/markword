test('quote, numbered list and divider keep a usable next writing position', async ({ page }) => {
  await single(page)
  await page.locator('.markdown-body [contenteditable]').focus()
  await slash(page, 'Quote')
  await active(page).fill('A new quote')
  await expect(page.locator('.markdown-body blockquote')).toHaveText('A new quote')
  await active(page).press('End')
  await active(page).press('Enter')
  await active(page).press('Enter')
  await slash(page, 'Numbered list')
  await active(page).fill('One')
  await active(page).press('End')
  await active(page).press('Enter')
  await active(page).fill('Two')
  await expect(page.locator('.markdown-body ol li')).toHaveText(['One', 'Two'])
  await page.locator('.markdown-append button').click()
  await slash(page, 'Divider')
  await active(page).fill('After the divider')
  await expect(page.locator('.markdown-body hr')).toHaveCount(1)
  await expect(page.locator('.markdown-body > p').last()).toHaveText('After the divider')
  await expect(page.locator('.save-status')).toHaveText('Saved in this browser')
  await page.reload()
  await expect(page.locator('.markdown-body blockquote')).toHaveText('A new quote')
  await expect(page.locator('.markdown-body ol li')).toHaveText(['One', 'Two'])
  await expect(page.locator('.markdown-body hr')).toHaveCount(1)
})

test('choosing a block on an empty list item preserves the other items', async ({ page }) => {
  await single(page, '- Keep this\n- Keep this too\n')
  await page.locator('.markdown-body li').last().locator('[contenteditable]').focus()
  await active(page).press('End')
  await active(page).press('Enter')
  await slash(page, 'Heading 2')
  await active(page).fill('Following section')
  await expect(page.locator('.markdown-body li')).toHaveText(['Keep this', 'Keep this too'])
  await expect(page.locator('.markdown-body h2')).toHaveText('Following section')
})
