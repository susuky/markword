import { expect, test, type Page } from '@playwright/test'

const active = (page: Page) => page.locator('.markdown-body [contenteditable]:focus')
async function single(page: Page, source = '') {
  await page.goto('/')
  await page.locator('.cm-content').fill(source)
  await page.getByRole('button', { name: 'Single-page editing', exact: true }).click()
}
async function slash(page: Page, name: string) {
  await active(page).press('/')
  await page.getByRole('dialog', { name: 'Add content' }).getByRole('button', { name, exact: true }).click()
}

test('write from an empty page, split a paragraph, merge and keep the source hidden', async ({ page }) => {
  await single(page)
  await page.locator('.markdown-body [contenteditable]').fill('First paragraph')
  await active(page).press('End')
  await active(page).press('Enter')
  await active(page).fill('Second paragraph')
  await active(page).press('Home')
  await active(page).press('ArrowRight')
  await active(page).press('ArrowRight')
  await active(page).press('ArrowRight')
  await active(page).press('Enter')
  await expect(page.locator('.markdown-body > p')).toHaveText(['First paragraph', 'Sec', 'ond paragraph'])
  await active(page).press('Backspace')
  await expect(page.locator('.markdown-body > p')).toHaveText(['First paragraph', 'Second paragraph'])
  await expect(page.locator('.pane--editor')).toBeHidden()
  await expect(page.locator('.save-status')).toHaveText('Saved in this browser')
  await page.reload()
  await expect(page.locator('.markdown-body > p')).toHaveText(['First paragraph', 'Second paragraph'])
})

test('slash menu creates headings, lists and exits an empty list item', async ({ page }) => {
  await single(page)
  await page.locator('.markdown-body [contenteditable]').focus()
  await slash(page, 'Heading 2')
  await active(page).fill('Meeting notes')
  await active(page).press('End')
  await active(page).press('Enter')
  await slash(page, 'To-do list')
  await active(page).fill('First task')
  await active(page).press('End')
  await active(page).press('Enter')
  await active(page).fill('Second task')
  await active(page).press('End')
  await active(page).press('Enter')
  await active(page).press('Enter')
  await active(page).fill('After tasks')
  await expect(page.locator('.markdown-body h2')).toHaveText('Meeting notes')
  await expect(page.locator('.markdown-body li')).toHaveText(['First task', 'Second task'])
  await expect(page.locator('.markdown-body input[type=checkbox]')).toHaveCount(2)
  await page.locator('.markdown-body input[type=checkbox]').first().check()
  await expect(page.locator('.markdown-body > p').last()).toHaveText('After tasks')
  await expect(page.locator('.pane--editor')).toBeHidden()
  await expect(page.locator('.save-status')).toHaveText('Saved in this browser')
  await page.reload()
  await expect(page.locator('.markdown-body input[type=checkbox]').first()).toBeChecked()
  await expect(page.locator('.markdown-body input[type=checkbox]').last()).not.toBeChecked()
})

test('insert code and a table, preserve later content, and undo a deleted block', async ({ page }) => {
  const original = '# Title\n\nBefore.\n\nUntouched  **spacing**.\n\n[ref]: https://example.com\n'
  await single(page, original)
  await page.locator('.markdown-body > p').first().locator('[contenteditable]').focus()
  await page.locator('.preview-header').getByRole('button', { name: 'Add content', exact: true }).click()
  await page.getByRole('dialog', { name: 'Add content' }).getByRole('button', { name: 'Code block', exact: true }).click()
  await page.getByRole('textbox', { name: 'Code block', exact: true }).fill('const answer = 42;')
  await page.getByRole('textbox', { name: 'Code block', exact: true }).press('Escape')
  await page.locator('.preview-header').getByRole('button', { name: 'Add content', exact: true }).click()
  await page.getByRole('dialog', { name: 'Add content' }).getByRole('button', { name: 'Table', exact: true }).click()
  const table = page.getByRole('dialog', { name: 'Edit table', exact: true })
  await table.getByRole('textbox', { name: 'Row 1, column 1', exact: true }).fill('New entry')
  await table.getByRole('button', { name: 'Apply changes', exact: true }).click()
  await expect(page.locator('.markdown-body table')).toContainText('New entry')
  await page.locator('.markdown-body h1 [contenteditable]').focus()
  await page.locator('.preview-header').getByRole('button', { name: 'Add content', exact: true }).click()
  await page.getByRole('button', { name: 'Delete block', exact: true }).click()
  await expect(page.locator('.markdown-body h1')).toHaveCount(0)
  await page.getByRole('button', { name: 'Preview editing tools', exact: true }).click()
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(page.locator('.markdown-body h1')).toHaveText('Title')
  await page.getByRole('button', { name: 'Split editing', exact: true }).click()
  await expect(page.locator('.cm-content')).toContainText('Untouched  **spacing**.')
  await expect(page.locator('.cm-content')).toContainText('[ref]: https://example.com')
})

