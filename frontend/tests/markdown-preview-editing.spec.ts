test('preview editing, tools and links keep both content areas aligned', async ({ page }) => {
  await page.setViewportSize({ width: 1600, height: 1000 })
  await page.goto('/')
  await page.locator('.cm-content').fill('* **Market Data**\n\n  * 歷史 Tick 載入\n  * [即時 Tick 接收](https://example.com)\n')
  await expect(preview(page).getByRole('link')).toBeVisible()
  const sourceBounds = (await page.locator('.editor-host').boundingBox())!
  const previewBounds = await page.locator('.preview-scroll').boundingBox()
  expect(previewBounds!.y).toBe(sourceBounds.y)
  expect(previewBounds!.height).toBe(sourceBounds.height)
  const firstText = await preview(page).locator('strong').boundingBox()
  const firstSourceLine = (await page.locator('.cm-line').first().boundingBox())!
  expect(Math.abs(firstText!.y - firstSourceLine.y)).toBeLessThan(4)
  await page.getByRole('button', { name: 'Preview editing tools', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeVisible()
  expect(await page.locator('.preview-scroll').boundingBox()).toEqual(previewBounds)
  expect(await preview(page).locator('strong').boundingBox()).toEqual(firstText)
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Preview editing tools', exact: true })).toBeFocused()
  await preview(page).getByRole('link').click()
  await page.getByLabel('Link address', { exact: true }).focus()
  expect(await page.locator('.preview-scroll').boundingBox()).toEqual(previewBounds)
  expect(await preview(page).locator('strong').boundingBox()).toEqual(firstText)
  await page.keyboard.press('Escape')
  await expect(page.locator('.markdown-link-form')).toHaveCount(0)
  await expect(preview(page).getByRole('link')).toBeFocused()
})

test('code editing preserves multiline input, fence safety, metadata and later blocks', async ({ page }) => {
  const original = '# Code\n\n```js title="example"\nconst original = 1;\n```\n\nUntouched **after**.\n\n| A | B |\n| --- | --- |\n| One | Two |\n'
  await start(page, original)
  const renderedCode = preview(page).getByRole('button', { name: 'Code block', exact: true })
  await renderedCode.click()
  const code = preview(page).getByRole('textbox', { name: 'Code block', exact: true })
  await code.fill('const value = 2;')
  await code.press('End')
  await code.press('Enter')
  await page.keyboard.insertText('console.log(value);')
  await code.press('Enter')
  await page.keyboard.insertText('```')
  await code.press('Control+Enter')
  await expect(code).toHaveCount(0)
  await expect(renderedCode.locator('.hljs-keyword').first()).toBeVisible()
  const changed = await download(page)
  expect(changed).toBe(original.replace('```js title="example"\nconst original = 1;\n```', '````js title="example"\nconst value = 2;\nconsole.log(value);\n```\n````'))
  await page.getByRole('button', { name: 'Preview editing tools', exact: true }).click()
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(renderedCode).not.toContainText('```')
  await page.getByRole('button', { name: 'Preview editing tools', exact: true }).click()
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  await expect(renderedCode).toContainText('console.log(value);')
  expect(await download(page)).toBe(changed)
  await preview(page).getByRole('button', { name: 'Edit table 1', exact: true }).click()
  await page.getByRole('textbox', { name: 'Row 1, column 2', exact: true }).fill('Edited')
  await page.getByRole('button', { name: 'Apply changes', exact: true }).click()
  expect(await download(page)).toBe(changed.replace('| One | Two |', '| One | Edited |'))
  await expect(page.locator('.save-status')).toHaveText('Saved in this browser')
  await page.reload()
  await expect(renderedCode).toHaveText('const value = 2;\nconsole.log(value);\n```\n')
})

test('empty and nested code blocks accept literal text without creating HTML or Markdown', async ({ page }) => {
  await start(page, '# Code\n\n~~~html\nold\n~~~\n\n> ```js\n> let n = 1;\n> ```\n\nAfter.\n')
  const renderedCodes = preview(page).getByRole('button', { name: 'Code block', exact: true })
  const code = preview(page).getByRole('textbox', { name: 'Code block', exact: true })
  await renderedCodes.first().click()
  await code.fill('')
  await code.press('Escape')
  await renderedCodes.first().click()
  await code.fill('<img src=x onerror=alert(1)>\n**literal**\n\nlast line\n')
  await code.press('Escape')
  await expect(renderedCodes.first().locator('img, strong')).toHaveCount(0)
  await renderedCodes.nth(1).click()
  await code.fill('let n = 2;\nconsole.log(n);')
  const result = await download(page)
  expect(result).toContain('~~~html\n<img src=x onerror=alert(1)>\n**literal**\n\nlast line\n~~~')
  expect(result).toContain('> ```js\n> let n = 2;\n> console.log(n);\n> ```')
  expect(result).toContain('\n\nAfter.\n')
  expect(result).not.toMatch(/contenteditable|Copy code/)
})
