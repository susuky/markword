test('typed markup stays literal, IME Enter keeps focus, and source changes rebuild editing', async ({ page }) => {
  await start(page, '# Original\n\nText.\n')
  const heading = preview(page).locator(`h1 ${text}`)
  await heading.fill('*literal* ~~keep~~ [text] $x$ <img src=x onerror=alert(1)>')
  await heading.dispatchEvent('keydown', { key: 'Enter', isComposing: true })
  await expect(heading).toBeFocused()
  await expect(page.locator('.save-status')).toHaveText('Saved in this browser')
  await page.reload()
  await expect(preview(page).locator('h1')).toHaveText('*literal* ~~keep~~ [text] $x$ <img src=x onerror=alert(1)>')
  await expect(preview(page).locator('h1 img, h1 em, h1 del, h1 .katex')).toHaveCount(0)
  await page.locator('.cm-content').fill('# Replaced from source\n\nNew text.\n')
  await expect(heading).toHaveText('Replaced from source')
  await heading.fill('Another edit')
  expect(await download(page)).toBe('# Another edit\n\nNew text.\n')
})

